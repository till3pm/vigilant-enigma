package com.example.androidpaperserver.server

import com.example.androidpaperserver.model.ServerInstance
import java.io.File

object ServerFiles {
    fun initialize(root: File, server: ServerInstance) {
        root.mkdirs()
        File(root, "server.properties").writeText(
            listOf(
                "server-port=${server.port}",
                "max-players=${server.maxPlayers}",
                "view-distance=${server.viewDistance}",
                "simulation-distance=${server.simulationDistance}",
                "motd=${server.motd}",
                "online-mode=true",
                "enable-command-block=false",
                "spawn-protection=16",
                "allow-flight=false"
            ).joinToString("\n") + "\n"
        )
        File(root, "eula.txt").writeText("# Generated by Paper Server Manager\neula=${server.eulaAccepted}\n")
        File(root, "plugins").mkdirs()
        File(root, "logs").mkdirs()
    }

    fun updateProperty(file: File, key: String, value: String) {
        val lines = if (file.exists()) file.readLines() else emptyList()
        val out = ArrayList<String>(); var found = false
        for (line in lines) {
            if (line.trimStart().startsWith("#") || !line.contains('=')) { out += line; continue }
            val k = line.substringBefore('=').trim()
            if (k == key) { out += "$key=$value"; found = true } else out += line
        }
        if (!found) out += "$key=$value"
        file.writeText(out.joinToString("\n") + "\n")
    }

    fun readProperties(file: File): Map<String, String> = if (!file.exists()) emptyMap() else file.readLines().mapNotNull { line ->
        val t = line.trim(); if (t.isEmpty() || t.startsWith("#") || !t.contains('=')) null
        else t.substringBefore('=').trim() to t.substringAfter('=').trim()
    }.toMap()
}
